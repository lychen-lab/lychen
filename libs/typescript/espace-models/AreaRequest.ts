import { type ObjectValues } from '@lychen/typescript-utils/transformers/ObjectValues';
import type { PersonName } from './PersonName';

/** Where a request stands, from its draft to its validation. */
export const AREA_REQUEST_STATUS = {
  Draft: 'draft',
  PendingValidation: 'pending_validation',
  Active: 'active',
  Rejected: 'rejected',
  Archived: 'archived',
} as const;

export type AreaRequestStatus = ObjectValues<typeof AREA_REQUEST_STATUS>;
export const AREA_REQUEST_STATUSES = Object.values(AREA_REQUEST_STATUS);

/** An area someone is looking for, as a list shows it. */
export interface AreaRequestSummary {
  uuid: string;
  title: string;
  description: string;
  /** In m². */
  minimalSurfaceRequested?: number;
  city?: string;
  /** Undefined for a status this front does not know yet. */
  status?: AreaRequestStatus;
  activityCodes: string[];
  requester?: PersonName;
}

/** An area someone is looking for, with everything its own page shows. */
export interface AreaRequest extends AreaRequestSummary {
  createdAt?: Date;
  archivedAt?: Date;
}

export interface AreaRequestCreateInput {
  /** Generated by the API when left out. */
  uuid?: string;
  title: string;
  description: string;
  /** In m². */
  minimalSurfaceRequested: number;
  city: string;
  activityCodes?: string[];
}

/** The fields to change; those left out are kept. */
export type AreaRequestUpdateInput = Partial<Omit<AreaRequestCreateInput, 'uuid'>>;
