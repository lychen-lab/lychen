import { type ObjectValues } from '@lychen/typescript-utils/transformers/ObjectValues';
import type { PersonName } from './PersonName';

/** Where a proposal stands, from its draft to its publication. */
export const AREA_PROPOSAL_STATUS = {
  Draft: 'draft',
  Verification: 'verification',
  Published: 'published',
  Archived: 'archived',
} as const;

export type AreaProposalStatus = ObjectValues<typeof AREA_PROPOSAL_STATUS>;
export const AREA_PROPOSAL_STATUSES = Object.values(AREA_PROPOSAL_STATUS);

/** An area someone offers to share, as a list shows it. */
export interface AreaProposalSummary {
  uuid: string;
  title: string;
  description: string;
  /** In m². */
  surfaceToShare?: number;
  city?: string;
  /** In metres. */
  altitude?: number;
  /** Undefined for a status this front does not know yet. */
  status?: AreaProposalStatus;
  activityCodes: string[];
  proposer?: PersonName;
}

/** An area someone offers to share, with everything its own page shows. */
export interface AreaProposal extends AreaProposalSummary {
  /** In m². */
  surfaceTotal?: number;
  createdAt?: Date;
  archivedAt?: Date;
}

export interface AreaProposalCreateInput {
  /** Generated by the API when left out. */
  uuid?: string;
  title: string;
  description: string;
  /** In m². */
  surfaceTotal: number;
  /** In m². */
  surfaceToShare: number;
  city: string;
  /** In metres. */
  altitude: number;
  activityCodes?: string[];
}

/** The fields to change; those left out are kept. */
export type AreaProposalUpdateInput = Partial<Omit<AreaProposalCreateInput, 'uuid'>>;
