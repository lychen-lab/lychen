import { type ObjectValues } from '@lychen/typescript-utils/transformers/ObjectValues';
import type { PersonName } from '../person/PersonName';

/** Where a request stands, from its draft to its validation. */
export const AREA_REQUEST_STATE = {
  Draft: 'draft',
  PendingValidation: 'pending_validation',
  Active: 'active',
  Archived: 'archived',
} as const;

export type AreaRequestState = ObjectValues<typeof AREA_REQUEST_STATE>;

/**
 * An area someone is looking for. Every field is optional: an endpoint says which ones it
 * gives, a component which ones it needs (`WithRequired`).
 */
export interface AreaRequest {
  id?: string;
  title?: string;
  description?: string;
  /** In m². */
  minimalSurfaceRequested?: number;
  city?: string;
  /** Undefined for a state this front does not know yet. */
  state?: AreaRequestState;
  activityCodes?: string[];
  requester?: PersonName;
  createdAt?: Date;
  archivedAt?: Date;
}

/** What the creation form gives. */
export interface AreaRequestCreateInput {
  /** Generated by the API when left out. */
  id?: AreaRequest['id'];
  title: NonNullable<AreaRequest['title']>;
  description: NonNullable<AreaRequest['description']>;
  minimalSurfaceRequested: NonNullable<AreaRequest['minimalSurfaceRequested']>;
  city: NonNullable<AreaRequest['city']>;
  activityCodes?: AreaRequest['activityCodes'];
}

/** The fields to change; those left out are kept. */
export type AreaRequestUpdateInput = Partial<Omit<AreaRequestCreateInput, 'id'>>;
