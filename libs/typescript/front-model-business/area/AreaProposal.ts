import { type ObjectValues } from '@lychen/typescript-utils/transformers/ObjectValues';
import type { PersonName } from '../person/PersonName';

/** Where a proposal stands, from its draft to its publication. */
export const AREA_PROPOSAL_STATE = {
  Draft: 'draft',
  Verification: 'verification',
  Published: 'published',
  Archived: 'archived',
} as const;

export type AreaProposalState = ObjectValues<typeof AREA_PROPOSAL_STATE>;

/**
 * An area someone offers to share. Every field is optional: an endpoint says which ones it
 * gives, a component which ones it needs (`WithRequired`).
 */
export interface AreaProposal {
  id?: string;
  title?: string;
  description?: string;
  /** In m². */
  surfaceTotal?: number;
  /** In m². */
  surfaceToShare?: number;
  city?: string;
  /** In metres. */
  altitude?: number;
  /** Undefined for a state this front does not know yet. */
  state?: AreaProposalState;
  activityCodes?: string[];
  proposer?: PersonName;
  createdAt?: Date;
  archivedAt?: Date;
}

/** What the creation form gives. */
export interface AreaProposalCreateInput {
  /** Generated by the API when left out. */
  id?: AreaProposal['id'];
  title: NonNullable<AreaProposal['title']>;
  description: NonNullable<AreaProposal['description']>;
  surfaceTotal: NonNullable<AreaProposal['surfaceTotal']>;
  surfaceToShare: NonNullable<AreaProposal['surfaceToShare']>;
  city: NonNullable<AreaProposal['city']>;
  altitude: NonNullable<AreaProposal['altitude']>;
  activityCodes?: AreaProposal['activityCodes'];
}

/** The fields to change; those left out are kept. */
export type AreaProposalUpdateInput = Partial<Omit<AreaProposalCreateInput, 'id'>>;
